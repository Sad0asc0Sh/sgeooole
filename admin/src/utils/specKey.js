const rawKey = (value) =>
  String(value ?? '')
    .replace(/[يئ]/g, 'ی')
    .replace(/ك/g, 'ک')
    .replace(/[آأإ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/[\u200c\s]+/g, '')
    .trim()
    .toLowerCase()

const SYNONYM_MAP = (() => {
  const map = new Map()
  for (const [canonical, aliases] of SYNONYM_GROUPS) {
    const target = rawKey(canonical)
    map.set(target, target)
    for (const alias of aliases) map.set(rawKey(alias), target)
  }
  return map
})()

export function normSpecKey(label) {
  const key = rawKey(label)
  return SYNONYM_MAP.get(key) ?? key
}

export default normSpecKey
